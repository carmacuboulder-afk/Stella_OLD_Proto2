-- Foreign Keys
ALTER TABLE teams
  ADD CONSTRAINT teams_owner_user_fk
  FOREIGN KEY (owner_user_id) REFERENCES users(id);

ALTER TABLE team_members
  ADD CONSTRAINT team_members_team_fk
  FOREIGN KEY (team_id) REFERENCES teams(id) ON DELETE CASCADE,
  ADD CONSTRAINT team_members_user_fk
  FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE;

ALTER TABLE uploads
  ADD CONSTRAINT uploads_user_fk
  FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE,
  ADD CONSTRAINT uploads_team_fk
  FOREIGN KEY (team_id) REFERENCES teams(id) ON DELETE SET NULL,
  ADD CONSTRAINT uploads_device_fk
  FOREIGN KEY (device_id) REFERENCES devices(id);

ALTER TABLE data
  ADD CONSTRAINT data_upload_fk
  FOREIGN KEY (upload_id) REFERENCES uploads(id) ON DELETE CASCADE,
  ADD CONSTRAINT data_device_fk
  FOREIGN KEY (device_id) REFERENCES devices(id);

-- Indexes to speed up queries
CREATE INDEX idx_team_members_user_id ON team_members(user_id);   -- Shows all teams from user
CREATE INDEX idx_team_members_team_id ON team_members(team_id);   -- Shows all users from team

CREATE INDEX idx_uploads_user_id ON uploads(user_id);             -- Shows all uploads from user
CREATE INDEX idx_uploads_team_id ON uploads(team_id);             -- Shows all uploads from team
CREATE INDEX idx_uploads_device_id ON uploads(device_id);         -- Shows all uploads from device
CREATE INDEX idx_uploads_timestamp ON uploads(timestamp_iso8601); -- Shows all uploads from specified date

CREATE INDEX idx_data_upload_id ON data(upload_id);               -- Show all data for this upload 
CREATE INDEX idx_data_device_id ON data(device_id);               -- Show all data for this device